### Convert all agents to tools in order to call them from the orchestrator ###
@tool
def call_puzzle_generator(task: str) -> str:
    """Generates escape room puzzles. Use this to create new riddles, math puzzles, or word puzzles."""
    response = puzzle_generator_agent.invoke({"input": task})
    return extract_response(response)

@tool
def call_game_state_manager(task: str) -> str:
    """Validates player answers. Use this to check if a player's answer is correct."""
    response = game_state_manager_agent.invoke({"input": task})
    return extract_response(response)

@tool
def call_hint_master(task: str) -> str:
    """Provides hints for puzzles. Use this when players need help."""
    response = hint_master_agent.invoke({"input": task})
    return extract_response(response)

@tool
def call_narrator(task: str) -> str:
    """Narrates the story. Use this for introductions, celebrations, failures, and endings."""
    response = narrator_agent.invoke({"input": task})
