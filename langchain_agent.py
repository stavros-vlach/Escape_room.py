    """Concludes the story based on success or failure via LLM."""
    if success:
        prompt = "Write a triumphant 2-3 sentence ending to an escape room story where the player successfully escaped the ancient temple."
    else:
        prompt = "Write a tragic 2-3 sentence ending to an escape room story where the player failed to escape the ancient temple."
    return model.invoke(prompt).content
    

