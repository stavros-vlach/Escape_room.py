def extract_response(response):
    """Extract text from various LangChain response formats."""
    # Handle dict with 'output' key
    if isinstance(response, dict) and 'output' in response:
        return response['output']
    # Handle dict with 'text' key
    if isinstance(response, dict) and 'text' in response:
        return response['text']
    # Handle AIMessage or similar objects with content attribute
    if hasattr(response, 'content'):
        return response.content
    # Handle string directly
    if isinstance(response, str):
        return response
    # Handle dict, try to find any text-like value
    if isinstance(response, dict):
        # Try 'messages' key for agent responses
        if 'messages' in response and isinstance(response['messages'], list) and response['messages']:
            last_msg = response['messages'][-1]
            if hasattr(last_msg, 'content'):
                return last_msg.content
            if isinstance(last_msg, dict) and 'content' in last_msg:
                return last_msg['content']
    # Fallback to string representation
    return str(response)

