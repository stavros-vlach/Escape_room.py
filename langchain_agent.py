# Now create orchestrator with these tools
orchestrator_agent = create_agent(
    model=model,
    system_prompt="""You orchestrate an escape room game.
    You use the following tools to generate puzzles, validate answers, provide hints, and narrate the story.
    Your goal is to create an engaging experience for the player as they attempt to escape by solving puzzles.
    Always decide the best next action based on the game state and player input.
    1. Use the narrator to set the scene and react to player progress.
    2. Use the puzzle generator to create new puzzles.
    3. Use the game state manager to validate player answers.
    4. Use the hint master to provide hints when requested. Inform the player about hint availability and how to ask for a hint.
    Keep track of the number of puzzles solved and remaining.
    Don't give many options to the player at once; guide them step-by-step through the game.
    First, start by introducing the game using the narrator tool.
    Then, generate only the first puzzle using the puzzle generator tool.
    Wait for player input before proceeding further.
    Check player's answers using the game state manager tool.
    If the player requests a hint, use the hint master tool to provide one.
    If the player solves a puzzle, celebrate using the narrator tool and generate the next puzzle.
    If the player fails to solve a puzzle and has more attempts, tell them to try again or ask for a hint.
    If the player fails to solve a puzzle and has no attempts left, narrate the failure and end the game.
    """,
    tools=[
        call_puzzle_generator,
        call_game_state_manager,
        call_hint_master,
        call_narrator
    ]
)


class OrchestratorState:
    def __init__(self, total_puzzles=3):
        self.chat_history = []
        self.game_state = {
            "current_puzzle": 1,
            "total_puzzles": total_puzzles,
            "puzzles_solved": 0,
            "current_attempts": 0,
            "max_attempts": 5,
            "hints_used": 0,
            "max_hints": 3,
            "current_puzzle_question": "",
            "current_puzzle_answer": "",  # ← Store answer here!
        }
    
    def invoke_orchestrator(self, user_message: str):
        """Invoke orchestrator with memory."""
        
        # Build context with current puzzle answer
        context = f"""[GAME STATE]
Puzzle: {self.game_state['current_puzzle']}/{self.game_state['total_puzzles']}
Attempts: {self.game_state['current_attempts']}/{self.game_state['max_attempts']}
Hints: {self.game_state['hints_used']}/{self.game_state['max_hints']}
Puzzles solved: {self.game_state['puzzles_solved']}

CURRENT PUZZLE QUESTION: {self.game_state['current_puzzle_question']}
CORRECT ANSWER: {self.game_state['current_puzzle_answer']}

[USER MESSAGE]
{user_message}"""
        
        response = orchestrator_agent.invoke({
            "input": context,
            "chat_history": self.chat_history
        })
        
        self.chat_history.append(("user", user_message))
        self.chat_history.append(("assistant", extract_response(response)))
        
        return extract_response(response)
    
    def generate_new_puzzle(self):
        """Generate puzzle and store the answer."""
        # Call puzzle generator directly (not through orchestrator)
        puzzle_response = call_puzzle_generator.invoke("Generate a random puzzle")
        
        # Parse to extract question and answer
        parsed = parse_puzzle_response.invoke(puzzle_response)
        
        # Store in state
        self.game_state["current_puzzle_question"] = parsed["question"]
        self.game_state["current_puzzle_answer"] = parsed["answer"].lower().strip()
        
        return parsed["question"]


# Main game loop
def play_game(num_puzzles=3):
    state = OrchestratorState(total_puzzles=num_puzzles)
    
    print("\n" + "="*70)
    print("AI-POWERED ESCAPE ROOM")
    print("="*70 + "\n")
    
    # Get introduction from narrator
    intro = state.invoke_orchestrator(
        f"Use call_narrator to introduce the game. Tell player they need to solve {num_puzzles} puzzles, can use 'hint' for hints (max 3 per puzzle), and have {state.game_state['max_attempts']} attempts per puzzle."
    )
    print(intro)
    
    input("\nPress Enter to continue...")
    
    # Main game loop
    while state.game_state["puzzles_solved"] < num_puzzles:
        print(f"\n{'='*70}")
        print(f"PUZZLE {state.game_state['current_puzzle']} of {num_puzzles}")
        print(f"{'='*70}\n")
        
        # Generate new puzzle and store answer
        puzzle_question = state.generate_new_puzzle()
        print(f"❓ {puzzle_question}\n")
        
        # Reset attempts for new puzzle
        state.game_state["current_attempts"] = 0
        state.game_state["hints_used"] = 0
        puzzle_solved = False
        
        # Puzzle attempt loop
        while state.game_state["current_attempts"] < state.game_state["max_attempts"] and not puzzle_solved:
            user_input = input(f"🔓 Your answer (Attempt {state.game_state['current_attempts'] + 1}/{state.game_state['max_attempts']}): ").strip()
            
            if user_input.lower() == "quit":
                print("Thanks for playing!")
                return
            
            # Handle hint request
            if user_input.lower() == "hint":
                if state.game_state["hints_used"] < state.game_state["max_hints"]:
                    state.game_state["hints_used"] += 1
                    
                    # Ask orchestrator to provide hint
                    response = state.invoke_orchestrator(
                        f"The player requested a hint (hint {state.game_state['hints_used']} of {state.game_state['max_hints']}). Use call_hint_master to provide a hint for the current puzzle."
                    )
                    print(f"\n💡 {response}\n")
                else:
                    print("❌ No more hints available!\n")
                continue
            
            # Increment attempts
            state.game_state["current_attempts"] += 1
            
            # Validate answer through orchestrator
            response = state.invoke_orchestrator(
                f"The player answered: '{user_input}'. Use call_game_state_manager to check if this answer is correct. The correct answer is: {state.game_state['current_puzzle_answer']}"
            )
            
            print(f"\n{response}\n")
            
            # Check if correct
            if "correct" in response.lower() or "right" in response.lower():
                puzzle_solved = True
                state.game_state["puzzles_solved"] += 1
                
                # Celebrate
                celebration = state.invoke_orchestrator(
                    "The player solved the puzzle! Use call_narrator to celebrate their success."
                )
                print(f"{celebration}\n")
                
                state.game_state["current_puzzle"] += 1
                break
            
            elif state.game_state["current_attempts"] >= state.game_state["max_attempts"]:
                # Game over
                failure = state.invoke_orchestrator(
                    f"The player failed after {state.game_state['max_attempts']} attempts. The correct answer was '{state.game_state['current_puzzle_answer']}'. Use call_narrator to dramatize their failure and end the game."
                )
                print(f"{failure}\n")
                return
            else:
                remaining = state.game_state["max_attempts"] - state.game_state["current_attempts"]
                print(f"❌ Incorrect. {remaining} attempts remaining.\n")
        
        if state.game_state["puzzles_solved"] < num_puzzles and puzzle_solved:
            input("\nPress Enter for the next puzzle...")
    
    # Victory!
    victory = state.invoke_orchestrator(
        "The player escaped! Use call_narrator to write a triumphant ending."
    )
    print(f"\n{victory}\n")
    
    print("="*70)
    print("🎉 CONGRATULATIONS! YOU ESCAPED! 🎉")
    print("="*70 + "\n")


if __name__ == "__main__":
    num = input("Number of puzzles (default 3): ")
    num_puzzles = int(num) if num.isdigit() else 3
    play_game(num_puzzles)