@tool
def check_player_answer(puzzle_question: str, correct_answer, player_answer) -> str:
    """Uses LLM to intelligently check if player's answer is correct, considering synonyms and variations."""
    prompt = f"""You are validating a player's answer to a puzzle.

PUZZLE QUESTION:
{puzzle_question}

CORRECT ANSWER:
{correct_answer}

PLAYER'S ANSWER:
{player_answer}

Determine if the player's answer is correct. Consider:
1. Exact matches (case-insensitive)
2. Synonyms or semantically equivalent answers
3. Minor spelling variations or typos
4. Alternative phrasings of the same answer

Examples:
- Correct: "keyboard" vs "key board" → CORRECT
- Correct: "echo" vs "an echo" → CORRECT  
- Correct: "4" vs "four" → CORRECT
- Incorrect: "joke" vs "laughter" → INCORRECT (different words)

Respond with ONLY "True" if correct or "False" if incorrect. No explanation and no additional text.
"""

    result = model.invoke(prompt)
    return result.content

