class Orchestrator:
  
    
    def __init__(self):
        self.game_state = {
            "total_puzzles": 0,
            "current_puzzle_index": 0,
            "puzzles": [],
            "current_attempts": 0,
            "max_attempts": 5,
            "hints_given": 0,
            "max_hints": 3
        }
    
    def play_game(self, num_puzzles: int = 3):
        """Main game loop with AI decision-making."""
        print("\n" + "="*70)
        print("AI-POWERED ESCAPE ROOM")
        print("="*70 + "\n")
        
        self.game_state["total_puzzles"] = num_puzzles
        game_state["unsolved_puzzles"] = list(range(num_puzzles))
        
        # Intro - Let narrator tell the story
        response = narrator_agent.respond(
            f"Tell the opening story. The player must solve {num_puzzles} puzzles to escape."
        )
        print(response)
        input("\nPress Enter to continue...")
        
        # Generate puzzles
        print("\n[Generating Puzzles...]")
        puzzles = []
        for i in range(num_puzzles):
            max_generation_attempts = 3
            valid_puzzle = None
            
            for attempt in range(max_generation_attempts):
                # Generate puzzle
                puzzle_response = puzzle_generator_agent.respond(f"Generate a random puzzle")
                
                # Extract text after agent name
                if "Puzzle_Generator:" in puzzle_response:
                    puzzle_text = puzzle_response.split("Puzzle_Generator:")[-1].strip()
                else:
                    puzzle_text = puzzle_response
                
                # Parse the puzzle
                parsed = parse_puzzle_response(puzzle_text)
                puzzle = {
                    "question": parsed["question"],
                    "answer": parsed["answer"].lower().strip()
                }
                
                # Validate the puzzle
                validation = validate_puzzle_with_llm(puzzle["question"], puzzle["answer"])
                
                if validation["valid"]:
                    valid_puzzle = puzzle
                    break
                else:
                    reason = validation['reason']
                    if validation.get('ambiguous'):
                        alts = validation.get('alternative_answers', [])
                        
                    
                    # If validator provides correct answer and it's not ambiguous, use it
                    if validation.get("correct_answer") and validation["correct_answer"] and not validation.get("ambiguous"):
                        puzzle["answer"] = validation["correct_answer"].lower().strip()
                        valid_puzzle = puzzle
                        break
                    
                    # Otherwise try again
                    if attempt < max_generation_attempts - 1:
                        print(f"Regenerating...")
            
            # If no valid puzzle after all attempts, use fallback
            if not valid_puzzle:
                print(f"Using fallback puzzle {i+1}")
                fallback_puzzles = [
                    {
                        "question": "I speak without a mouth and hear without ears. What am I?",
                        "answer": "echo"
                    },
                    {
                        "question": "What has keys but no locks, space but no room, and you can enter but can't go inside?",
                        "answer": "keyboard"
                    },
                    {
                        "question": "I'm tall when I'm young and short when I'm old. What am I?",
                        "answer": "candle"
                    }
                ]
                valid_puzzle = fallback_puzzles[i % len(fallback_puzzles)]
            
            puzzles.append(valid_puzzle)
        
        self.game_state["puzzles"] = puzzles
        
        # Play each puzzle
        for puzzle_idx, puzzle in enumerate(puzzles):
            print(f"\n{'='*70}")
            print(f"PUZZLE {puzzle_idx + 1}/{num_puzzles}")
            print(f"{'='*70}\n")
            
            self.game_state["current_puzzle_index"] = puzzle_idx
            self.game_state["current_attempts"] = 0
            self.game_state["hints_given"] = 0
            
            # Use hint master agent to reset hints for new puzzle
            hint_master_agent.respond(f"Reset the hints for puzzle {puzzle_idx + 1}")
            
            puzzle_solved = False
            
            while self.game_state["current_attempts"] < self.game_state["max_attempts"] and not puzzle_solved:
                # Display puzzle
                print(f"❓ {puzzle['question']}\n")
                
                # Get player input
                user_input = input(f"🔓 Your answer (Attempt {self.game_state['current_attempts'] + 1}/{self.game_state['max_attempts']}): ").strip()
                
                if user_input.lower() == "quit":
                    print("\nThanks for playing!")
                    return
                
                # Handle hint request
                if user_input.lower() == "hint":
                    if self.game_state["hints_given"] < self.game_state["max_hints"]:
                        self.game_state["hints_given"] += 1
                        
                        # Let hint master provide the hint (no attempt_count needed - uses global state)
                        hint_request = f"""Provide a hint for the following puzzle:

Puzzle Question: {puzzle['question']}
Puzzle Answer: {puzzle['answer']}
Attempt Number: {self.game_state['current_attempts']}"""

                        response = hint_master_agent.respond(hint_request)
                        print(f"\n💡 {response}\n")
                    else:
                        print("❌ No more hints available!\n")
                    continue
                
                # Let AI validate the answer
                self.game_state["current_attempts"] += 1
                
                # Ask game state manager to validate
                validation_request = f"""Check if the player's answer is correct.

Puzzle Question: {puzzle['question']}
Correct Answer: {puzzle['answer']}
Player's Answer: {user_input}
Current Attempts: {self.game_state['current_attempts']}/{self.game_state['max_attempts']}
"""

                response = game_state_manager_agent.respond(validation_request)
                response = response.lower()
                
                if "true" in response:
                    puzzle_solved = True
                    game_state["solved_puzzles"].append(puzzle_idx)
                    if puzzle_idx in game_state["unsolved_puzzles"]:
                        game_state["unsolved_puzzles"].remove(puzzle_idx)
                    
                    # Let narrator celebrate
                    celebration = narrator_agent.respond(
                        f"The player solved the puzzle! Celebrate their success."
                    )
                    print(f"\n{celebration}\n")
                    
                elif self.game_state["current_attempts"] >= self.game_state["max_attempts"]:
                    # Max attempts reached - game over
                    failure = narrator_agent.respond(
                        f"The player failed after {self.game_state['max_attempts']} attempts. The correct answer was '{puzzle['answer']}'. Dramatize their failure and end the game."
                    )
                    print(f"\n{failure}\n")
                    return
                    
                else:
                    # Still have attempts left
                    remaining = self.game_state["max_attempts"] - self.game_state["current_attempts"]
                    print(f"❌ Incorrect. {remaining} attempts remaining.\n")
            
            if puzzle_idx < len(puzzles) - 1 and puzzle_solved:
                input("\nPress Enter for the next puzzle...")
        
        # Victory!
        response = narrator_agent.respond("Write a triumphant ending - the player escaped!")
        print(f"\n{response}\n")
        
        print("\n" + "="*70)
        print("🎉 CONGRATULATIONS! YOU ESCAPED! 🎉")
        print("="*70 + "\n")


