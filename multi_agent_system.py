class GPTModel:
    def __init__(self, model_name, api_key):
        self.client = OpenAI(api_key=api_key)
        self.model_name = model_name

    def run(self, prompt):
        response = self.client.chat.completions.create(
            model=self.model_name,
            messages=[{"role": "user", "content": prompt}]
        )
        return response.choices[0].message.content
    
gpt = GPTModel(model_name="gpt-4o-mini", api_key=os.getenv("OPENAI_API_KEY"))

class Puzzle_Agent:
    def __init__(self, name:str, role:str, tools: List[callable]):
        self.name = name
        self.role = role
        self.tools = {tool.__name__: tool for tool in tools}

    def respond(self, message: str) -> str:
        # Create tool descriptions for the model
        tool_descriptions = []
        for tool_name, tool in self.tools.items():
            sig = inspect.signature(tool)
            properties = {}
            required = []
            
            for param_name, param in sig.parameters.items():
                properties[param_name] = {
                    "type": "string",
                    "description": f"Parameter: {param_name}"
                }
                if param.default == inspect.Parameter.empty:
                    required.append(param_name)
            
            if not properties:
                properties = {}
                required = []
            
            tool_descriptions.append({
                "type": "function",   
                "function": {
                    "name": tool_name,
                    "description": tool.__doc__ or f"Call the {tool_name} function",
                    "parameters": {
                        "type": "object",
                        "properties": properties,
                        "required": required
                    }
                }
            })

        # Call OpenAI with function calling
        response = openai.chat.completions.create(
            model="gpt-4o-mini",
            messages=[
                {"role": "system", "content": self.role},
                {"role": "user", "content": message}
            ],
            tools=tool_descriptions,
            tool_choice="auto"  # Let the model decide when to use tools
        )

        # Handle function calls
        if response.choices[0].message.tool_calls:
            tool_call = response.choices[0].message.tool_calls[0]
            function_name = tool_call.function.name
            arguments = json.loads(tool_call.function.arguments)

            # Execute the function
            if function_name in self.tools:
                func = self.tools[function_name]
                # Call function with appropriate arguments
                if arguments:
                    result = func(**arguments)
                else:
                    result = func()
                return f"{self.name}: {result}"

        # Regular response if no function call
        return f"{self.name}: {response.choices[0].message.content}"

### Puzzle generation and validation tools ###    
def generate_riddle() -> str:
    """Returns a riddle puzzle (question + correct answer) generated by LLM."""
    prompt = "Generate a single riddle puzzle for an escape room. Format: RIDDLE: [riddle question] ANSWER: [short answer]"
    return gpt.run(prompt)

def generate_math_puzzle() -> str:
    """Returns a math puzzle (question + correct answer) generated by LLM."""
    prompt = "Generate a single math puzzle for an escape room. Format: PUZZLE: [math question] ANSWER: [numerical answer]"
    return gpt.run(prompt)

def generate_word_puzzle() -> str:
    """Returns a word puzzle (question + correct answer) generated by LLM."""
    prompt = "Generate a single word puzzle for an escape room. Format: PUZZLE: [word puzzle question] ANSWER: [short word answer]"
    return gpt.run(prompt)

def random_puzzle(type=None):
    """Picks a puzzle type at random (or based on type) and generates via LLM."""
    if type == "riddle":
        return generate_riddle()
    elif type == "math":
        return generate_math_puzzle()
    elif type == "word":
        return generate_word_puzzle()
    else:
        puzzle_func = random.choice([generate_riddle, generate_math_puzzle, generate_word_puzzle])
        return puzzle_func()

def parse_puzzle_response(response):
    """Uses LLM to intelligently extract question and answer from puzzle response."""
    prompt = f"""You are a puzzle extractor. Given a puzzle text that contains both a question and an answer, 
extract them separately and return ONLY this format (nothing else):
QUESTION: [the puzzle question without the answer]
ANSWER: [the correct answer - just the answer value, nothing else]

Puzzle to extract from:
{response}"""
    
    result = gpt.run(prompt)
    
    # Parse the LLM's extraction
    
    question_match = re.search(r'QUESTION:\s*(.+?)(?=ANSWER:|$)', result, re.IGNORECASE | re.DOTALL)
    answer_match = re.search(r'ANSWER:\s*(.+?)$', result, re.IGNORECASE | re.DOTALL)
    
    question = question_match.group(1).strip() if question_match else response.strip()
    answer = answer_match.group(1).strip() if answer_match else ""
    
    return {"question": question, "answer": answer}

def validate_puzzle_with_llm(puzzle_question: str, puzzle_answer: str) -> dict:
    """
    Use LLM to validate that the answer actually solves the puzzle.
    Returns: {"valid": True/False, "reason": "explanation"}
    """
    prompt = f"""You are a puzzle validator. Check if the provided answer actually solves the puzzle.

PUZZLE QUESTION:
{puzzle_question}

PROVIDED ANSWER:
{puzzle_answer}

Analyze carefully:
1. Read the puzzle question thoroughly
2. Solve it yourself step-by-step
3. Check if there are multiple possible answers
4. Verify the provided answer is correct and unambiguous
5. If multiple answers are possible, the puzzle is INVALID (ambiguous)

Respond with ONLY this JSON format:
{{
    "valid": true or false,
    "reason": "brief explanation",
    "correct_answer": "the correct answer if provided one is wrong, otherwise null",
    "ambiguous": true or false,
    "alternative_answers": ["list", "of", "other", "possible", "answers"] or null
}}

CRITICAL: If a puzzle has multiple valid answers (like "joke" vs "laughter" vs "riddle"), mark it as INVALID with ambiguous=true."""

    try:
        client = OpenAI(api_key=os.getenv("OPENAI_API_KEY"))
        response = client.chat.completions.create(
            model="gpt-4o-mini",
            messages=[{"role": "user", "content": prompt}],
            response_format={"type": "json_object"}
        )
        result = json.loads(response.choices[0].message.content)
        
        # If ambiguous, mark as invalid
        if result.get("ambiguous", False):
            result["valid"] = False
            if not result.get("reason"):
                result["reason"] = "Puzzle has multiple possible answers (ambiguous)"
        
        return result
    except Exception as e:
        return {
            "valid": False,
            "reason": f"Validation error: {e}",
            "correct_answer": None,
            "ambiguous": False
        }

