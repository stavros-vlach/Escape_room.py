def check_player_answer(puzzle_question: str, correct_answer, player_answer) -> str:
    """Uses LLM to intelligently check if player's answer is correct, considering synonyms and variations."""
    prompt = f"""You are validating a player's answer to a puzzle.

PUZZLE QUESTION:
{puzzle_question}

CORRECT ANSWER:
{correct_answer}

PLAYER'S ANSWER:
{player_answer}

Determine if the player's answer is correct. Consider:
1. Exact matches (case-insensitive)
2. Synonyms or semantically equivalent answers
3. Minor spelling variations or typos
4. Alternative phrasings of the same answer

Examples:
- Correct: "keyboard" vs "key board" → CORRECT
- Correct: "echo" vs "an echo" → CORRECT  
- Correct: "4" vs "four" → CORRECT
- Incorrect: "joke" vs "laughter" → INCORRECT (different words)

Respond with ONLY "True" if correct or "False" if incorrect. No explanation and no additional text.
"""

    result = gpt.run(prompt)
    return result

### Hint Master Agent tools ###

# Global hint state tracking
hint_state = {
    "current_puzzle_id": None,
    "hints_given_count": 0
}

def get_hint(puzzle_question: str, puzzle_answer: str, attempt_count: str) -> str:
    """Provides a hint based on the puzzle question, answer, and number of attempts via LLM."""
    # Increment the hint counter in global state
    hint_state["hints_given_count"] += 1
    attempt_level = hint_state["hints_given_count"]
    
    # Cap at 5 levels
    attempt_level = min(attempt_level, 5)
    
    hint_instructions = {
        1: "Give a very subtle hint that guides toward the solution type. Reference something specific about the puzzle question.",
        2: "Give a hint that points toward a specific aspect of the puzzle. Use elements from the puzzle question to guide them.",
        3: "Give a more direct hint. Reference the puzzle question and guide significantly toward the answer type.",
        4: "Give a very direct hint. You can mention what category the answer falls into or give a strong clue about the answer.",
        5: "Give a hint that's almost the answer. You can reveal part of the answer or describe it very explicitly."
    }
    
    prompt = f"""You are a hint master for escape room puzzles.

PUZZLE QUESTION: {puzzle_question}
CORRECT ANSWER: {puzzle_answer}
HINT LEVEL: {attempt_level}

{hint_instructions[attempt_level]}

CRITICAL RULES:
1. Use the ACTUAL puzzle question and answer above to create your hint
2. Reference specific words or concepts from the puzzle question
3. Do NOT give generic hints like "think carefully" or "look for patterns"
4. Your hint must guide toward the specific answer: {puzzle_answer}
5. Keep it to 1-2 sentences maximum

Provide ONLY the hint text, nothing else:"""
    
    return gpt.run(prompt)

def reset_hints(puzzle_id: str = "new_puzzle"):
    """Resets hint progression for a new puzzle."""
    hint_state["current_puzzle_id"] = puzzle_id
    hint_state["hints_given_count"] = 0
    return f"Hints have been reset for puzzle: {puzzle_id}"

### Narrator Agent tools ###
def intro_story():
    """Sets the opening scene via LLM narrative."""
    prompt = f"""You are a narrator for an escape room adventure.

        First, greet the player and explain the game:
        - They need to solve {num_puzzles} puzzles to escape the ancient temple
        - They can type 'hint' to get up to 3 hints per puzzle
        - They have 5 attempts per puzzle

        Then, create an immersive opening scene (2-3 sentences) that sets the mood for the ancient temple escape room.

        Be dramatic and engaging!"""
    return gpt.run(prompt)

def narrate_success(puzzle):
    """Narrates success after solving a puzzle via LLM."""
    prompt = f"Narrate in 1-2 sentences how the player successfully solved this puzzle: {puzzle}. Use dramatic, celebratory language."
    return gpt.run(prompt)

def narrate_failure(puzzle):
    """Adds drama when the player fails to solve a puzzle via LLM."""
    prompt = f"Write 1-2 sentences of dramatic narration about the player failing to solve this puzzle: {puzzle}. The temple is trapping them."
    return gpt.run(prompt)

def ending(success=True):
    """Concludes the story based on success or failure via LLM."""
    if success:
        prompt = "Write a triumphant 2-3 sentence ending to an escape room story where the player successfully escaped the ancient temple."
    else:
        prompt = "Write a tragic 2-3 sentence ending to an escape room story where the player failed to escape the ancient temple."
    return gpt.run(prompt)

